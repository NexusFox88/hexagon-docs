import {HarnessImages} from '../../modules/harnesses/images.js';
import {consoleRelease} from '../../modules/deployment/console-release.js';
import {fileURLToPath} from 'node:url';
import {LocalAccess} from '../../modules/credentials/local-access.js';
import {publishLocalDiscovery} from '../../modules/deployment/local-discovery.js';
import {configureOutboundProxy} from '../../modules/deployment/outbound.js';
import {deploymentMode} from '../../modules/deployment/mode.js';
import {DeploymentSettings,deploymentEnvironment} from '../../modules/deployment/settings.js';
import {CredentialReadiness} from '../../modules/deployment/credential-readiness.js';
import {DevelopmentIngress} from '../../modules/deployment/ingress.js';
import { CredentialIngressHealth } from '../../modules/access/ingress-health.js';
import { openCloudflareCredentialTunnel } from '../../integrations/network/cloudflare-tunnel.js';
import { createAccessServer } from './access-server.js';
import { ConnectionAccess } from '../../modules/access/access.js';
import { sandboxConnections, createSandboxConnector } from '../../integrations/sandboxes/registry.js';
import { HarnessPackages } from '../../modules/execution/harness-packages.js';
import { piAdapter } from '../../integrations/harnesses/pi.js';
import { HarnessRegistry } from '../../modules/execution/harness.js';
import { Previews } from '../../modules/sandboxes/previews.js';
import { createPreviewServer } from './preview-server.js';
import { httpToolConnection } from '../../integrations/tools/http-json.js';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { openDatabase } from '../../modules/storage/database.js';
import { initializeOwner, authenticateIdentity } from '../../modules/credentials/api-auth.js';
import { loadLocalCipher, SecretStore } from '../../modules/credentials/secret-store.js';
import { Connections } from '../../modules/connections/connections.js';
import { Sessions } from '../../modules/execution/sessions.js';
import { createServer } from './server.js';
import { SandboxLifecycle } from '../../modules/sandboxes/lifecycle.js';
import {responsesModelConnection} from '../../integrations/models/openai-responses.js';
import {openaiModelConnection} from '../../integrations/models/openai-compatible.js';
import { anthropicModelConnection } from '../../integrations/models/anthropic-compatible.js';
import { openCodeAdapter } from '../../integrations/harnesses/opencode.js';
import { ExecutionWorker } from '../../modules/execution/worker.js';

const mode=deploymentMode(process.env);
const data = resolve(process.env.HEXAGON_DATA_DIR ?? '.local/control-plane');
const deployment = new DeploymentSettings(data);
const initialDeployment = mode.mode==='local'?await deployment.read():undefined;
if(initialDeployment)Object.assign(process.env,deploymentEnvironment(initialDeployment.config,process.env));
const outbound=configureOutboundProxy(process.env);
if(mode.mode==='local')await mkdir(data, { recursive: true, mode: 0o700 });
const cipher = mode.mode==='hosted'?mode.cipher:await loadLocalCipher(resolve(data, 'master.key'));
const pool = openDatabase(process.env.DATABASE_URL ?? 'postgres://hexagon@127.0.0.1:55432/hexagon');
if(mode.mode==='hosted'){const identity=await authenticateIdentity(pool,`Bearer ${mode.token}`);if(!identity||identity.role!=='owner')throw new Error('hosted_owner_identity_required');}
const owner = mode.mode==='local'?await initializeOwner(pool):null;
if (owner) {
  await writeFile(resolve(data, 'owner.json'), JSON.stringify(owner), { mode: 0o600, flag: 'wx' });
  process.stdout.write(`Initial API access saved to ${resolve(data, 'owner.json')} (private file).\n`);
}
const secrets = new SecretStore(pool, cipher);
const connections = new Connections(pool, secrets, [...sandboxConnections, anthropicModelConnection, openaiModelConnection, responsesModelConnection, httpToolConnection]);
const harnesses = new HarnessRegistry([openCodeAdapter, piAdapter], new HarnessPackages(pool), new HarnessImages(pool,secrets));
const lifecycle = new SandboxLifecycle(pool, secrets, createSandboxConnector);
const accessApp=createAccessServer(new ConnectionAccess(pool,secrets));
const accessAddress=await accessApp.listen({host:process.env.HEXAGON_ACCESS_HOST??'127.0.0.1',port:Number(process.env.HEXAGON_ACCESS_PORT??8789)});
const ingress = new DevelopmentIngress(()=>openCloudflareCredentialTunnel(accessAddress),origin=>{process.env.HEXAGON_ACCESS_URL=origin;});
if(process.env.HEXAGON_ACCESS_TUNNEL && process.env.HEXAGON_ACCESS_TUNNEL!=='cloudflare')throw new Error('unsupported_credential_tunnel');
const previews = new Previews(pool, lifecycle, { scheme: process.env.PREVIEW_SCHEME ?? 'http', domain: process.env.PREVIEW_DOMAIN ?? 'localhost', port: Number(process.env.PREVIEW_PORT ?? 8788) });
const previewApp = createPreviewServer(previews);
await previewApp.listen({ host: process.env.PREVIEW_HOST ?? '127.0.0.1', port: Number(process.env.PREVIEW_PORT ?? 8788) });
const ingressHealth=new CredentialIngressHealth(()=>connections.access().configuration());
const readiness=new CredentialReadiness(ingressHealth,ingress,process.env.HEXAGON_ACCESS_TUNNEL==='cloudflare',async()=>!(await pool.query("SELECT 1 FROM runs r JOIN run_invocations i ON i.tenant_id=r.tenant_id AND i.run_id=r.id WHERE r.state NOT IN ('completed','failed','cancelled') LIMIT 1")).rowCount);
const sessions = new Sessions(pool, connections, harnesses, secrets,()=>readiness.ensure());
const worker = new ExecutionWorker(pool, secrets, lifecycle, harnesses,()=>readiness.ensure());
const localAccess=mode.mode==='local'&&['127.0.0.1','localhost','::1'].includes(process.env.HOST??'127.0.0.1')?new LocalAccess(data):undefined;
const release=await consoleRelease(fileURLToPath(new URL('../console/',import.meta.url)));
const app = createServer(pool, { harnessImages:new HarnessImages(pool,secrets), consoleRelease:release,localAccess,connections, sessions, lifecycle, previews, ...(mode.mode==='local'?{deployment,deploymentRevision:initialDeployment?.revision,ingress}:{}), accessHealth:async()=>({...await ingressHealth.check(),recovery:readiness.status()}), workerHealth: () => worker.health(), credentialHealth: tenant => secrets.health(tenant) });
const apiAddress=await app.listen({ host: process.env.HOST ?? '127.0.0.1', port: Number(process.env.PORT ?? 8787) });
if(localAccess)await publishLocalDiscovery(data,apiAddress);
worker.start();
if(process.env.HEXAGON_ACCESS_TUNNEL==='cloudflare'){void ingress.start();readiness.start();}
process.stdout.write('Hexagon API and execution worker running.\n');
for (const signal of ['SIGINT', 'SIGTERM'] as const) process.once(signal, async () => { readiness.stop(); await worker.stop(); await app.close(); await previewApp.close(); await ingress.close(); await accessApp.close(); await pool.end(); await outbound.close(); });
